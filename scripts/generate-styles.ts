/**
 * Writes `src/styles/colors.css` and `src/styles/theme.css`.
 * Run with `bun run generate` after changing the color list or the defaults.
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { colors } from '../src/lib/colors'
import { grays, type Radius } from '../src/lib/theme'

const DEFAULT_ACCENT = 'blue'
const DEFAULT_GRAY = 'slate'

// Bright scales where white text on step 9 is hard to read (same as Radix Themes)
const darkContrast: Record<string, string> = {
  amber: '#21201c',
  yellow: '#21201c',
  lime: '#1d211c',
  mint: '#1a211e',
  sky: '#1c2024',
}

// Same sizes as Tailwind's rounded-xs ... rounded-xl
const radius = { xs: '0.125rem', sm: '0.25rem', md: '0.375rem', lg: '0.5rem', xl: '0.75rem' }

// Same factors as Radix Themes
const radiusFactor: Record<Radius, number> = {
  none: 0,
  small: 0.75,
  medium: 1,
  large: 1.5,
  full: 1.5,
}

const steps = Array.from({ length: 12 }, (_, index) => index + 1)
const header = '/* Generated by scripts/generate-styles.ts. Do not edit by hand. */\n'
const themes = ':root, .light, .light-theme, .dark, .dark-theme'

function scale(slot: string, name: string) {
  return [
    ...steps.map((step) => `  --${slot}-${step}: var(--${name}-${step});`),
    ...steps.map((step) => `  --${slot}-a${step}: var(--${name}-a${step});`),
  ]
}

function accent(name: string) {
  return [...scale('accent', name), `  --accent-contrast: ${darkContrast[name] ?? '#fff'};`]
}

// colors.css
const imports = [...colors, ...grays].flatMap((name) =>
  ['', '-alpha', '-dark', '-dark-alpha'].map(
    (suffix) => `@import "@radix-ui/colors/${name}${suffix}.css";`,
  ),
)

writeFileSync(
  join(import.meta.dirname, '../src/styles/colors.css'),
  `${header}\n${imports.join('\n')}\n`,
)

// theme.css
const tokens = (slot: string) => [
  ...steps.map((step) => `  --color-${slot}-${step}: var(--${slot}-${step});`),
  ...steps.map((step) => `  --color-${slot}-a${step}: var(--${slot}-a${step});`),
]

const theme = [
  header,
  '/* Tailwind utilities: bg-accent-9, text-gray-11, border-accent-a7, ... */',
  '@theme inline {',
  ...tokens('accent'),
  '  --color-accent-contrast: var(--accent-contrast);',
  ...tokens('gray'),
  '',
  '  /* Surfaces: bg-panel (popups, cards), bg-surface (inputs), bg-overlay (backdrops) */',
  '  --color-panel: var(--panel);',
  '  --color-surface: var(--surface);',
  '  --color-overlay: var(--overlay);',
  '}',
  '',
  '/*',
  ' * Corner radius that follows the theme: rounded-ui-sm, rounded-ui-md, ...',
  ' * Each one also sets --ui-radius on the element, so a part inside it can',
  ' * match the curve, for example rounded-[calc(var(--ui-radius)-1px)].',
  ' */',
  ...Object.entries(radius).flatMap(([name, size]) => [
    `@utility rounded-ui-${name} {`,
    `  --ui-radius: max(calc(${size} * var(--radius-factor)), var(--radius-full));`,
    '  border-radius: var(--ui-radius);',
    '}',
    '',
  ]),
  '/*',
  ' * For boxes that hold content (dialogs, popups, cards): rounded-panel-md, ...',
  ' * Same as rounded-ui-* but never a pill, also when the theme radius is full.',
  ' */',
  ...Object.entries(radius).flatMap(([name, size]) => [
    `@utility rounded-panel-${name} {`,
    `  --ui-radius: calc(${size} * var(--radius-factor));`,
    '  border-radius: var(--ui-radius);',
    '}',
    '',
  ]),
  '/* For switches and slider thumbs: round unless the theme radius is none or small */',
  '@utility rounded-ui-thumb {',
  '  --ui-radius: max(calc(0.25rem * var(--radius-factor)), var(--radius-thumb));',
  '  border-radius: var(--ui-radius);',
  '}',
  '',
  '/* Defaults. Set again on every theme class, so nested light/dark areas work. */',
  `${themes} {`,
  ...accent(DEFAULT_ACCENT),
  ...scale('gray', DEFAULT_GRAY),
  '}',
  '',
  '/* Surfaces (same values as Radix Themes) */',
  ':root, .light, .light-theme {',
  '  --panel: #fff;',
  '  --surface: rgb(255 255 255 / 0.85);',
  '  --overlay: rgb(0 0 0 / 0.4);',
  '}',
  '',
  '.dark, .dark-theme {',
  '  --panel: var(--gray-2);',
  '  --surface: rgb(0 0 0 / 0.25);',
  '  --overlay: rgb(0 0 0 / 0.7);',
  '}',
  '',
  '/* The theme gray: data-gray points the gray at another scale. */',
  ...grays.flatMap((name) => [
    `[data-gray="${name}"],`,
    `[data-gray="${name}"] :where(.light, .light-theme, .dark, .dark-theme) {`,
    ...scale('gray', name),
    '}',
    '',
  ]),
  '/* The theme radius */',
  ':root {',
  '  --radius-factor: 1;',
  '  --radius-full: 0px;',
  '  --radius-thumb: 9999px;',
  '}',
  '',
  ...Object.entries(radiusFactor).flatMap(([name, factor]) => [
    `[data-radius="${name}"] {`,
    `  --radius-factor: ${factor};`,
    `  --radius-full: ${name === 'full' ? '9999px' : '0px'};`,
    `  --radius-thumb: ${name === 'none' || name === 'small' ? '0px' : '9999px'};`,
    '}',
    '',
  ]),
  '/* The `color` prop: data-color points the accent at another scale. */',
  ...colors.flatMap((name) => [
    `[data-color="${name}"],`,
    `[data-color="${name}"] :where(.light, .light-theme, .dark, .dark-theme) {`,
    ...accent(name),
    '}',
    '',
  ]),
]

writeFileSync(join(import.meta.dirname, '../src/styles/theme.css'), theme.join('\n'))
